export function findMatchingStockMedia(keywords: string[] = []): StockMediaItem {
  if (!keywords || keywords.length === 0) {
    return STOCK_MEDIA_COLLECTION[0];
  }
  const lowerKeys = keywords.map((k) => k.toLowerCase());
  let bestMatch = STOCK_MEDIA_COLLECTION[0];
  let maxScore = -1;

  for (const item of STOCK_MEDIA_COLLECTION) {
    let score = 0;
    for (const tag of item.tags) {
      for (const k of lowerKeys) {
        if (tag.includes(k) || k.includes(tag)) {
          score += 3;
        }
      }
    }
    for (const k of lowerKeys) {
      if (item.title.toLowerCase().includes(k) || item.category.toLowerCase().includes(k)) {
        score += 2;
      }
    }
    if (score > maxScore) {
      maxScore = score;
      bestMatch = item;
    }
  }

  return bestMatch;
}
